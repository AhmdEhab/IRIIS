import { chromium } from 'playwright';
import { mkdirSync } from 'fs';
const WEB = 'http://127.0.0.1:5173';
const API = 'http://127.0.0.1:5000/api';
const OUT = '/home/ubuntu/iris-delivery/navigation';
mkdirSync(OUT, { recursive: true });
const J = async (m, u, b, t) => { const r = await fetch(u, { method: m, headers: { 'Content-Type': 'application/json', ...(t ? { Authorization: `Bearer ${t}` } : {}) }, body: b ? JSON.stringify(b) : undefined }); let d = null; try { d = await r.json(); } catch { } return { status: r.status, data: d }; };
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 1280, height: 940 } });
const page = await ctx.newPage();
const email = `vis-${Date.now()}@example.com`;
const r = await J('POST', `${API}/register`, { email, password: 'Passw0rd1', name: 'Visual Kid', age: 5, condition: 'other', consent_mvp_use: true });
const token = r.data.token, kid = r.data.child?.id;
await J('POST', `${API}/verify/confirm`, { code: r.data.verification.devCode }, token);
const scoredStub = { bankVersion: 'cv2', completeness: { coreAnswered: 13, coreTotal: 13, followUpsAnswered: 2 }, domainStates: { C: { state: 'emerging', confidence: 'MEDIUM' }, L: { state: 'developing', confidence: 'MEDIUM' }, S: { state: 'emerging', confidence: 'MEDIUM' }, M: { state: 'independent', confidence: 'LOW' }, P: { state: 'developing', confidence: 'MEDIUM' }, H: { state: 'steady', confidence: 'MEDIUM' } }, accessSettings: [], interests: ['عجلات'], plans: [], careFlags: [], guidanceNotes: [] };
await J('POST', `${API}/assessments`, { childId: kid, assessment_kind: 'CAREGIVER', clientRef: 'vis-cg', item_results: { responses: { VQ1: 'a' }, scored: scoredStub } }, token);
await J('POST', `${API}/assessments`, { childId: kid, assessment_kind: 'LADDER', clientRef: 'vis-ld', item_results: { stub: true, items: [] } }, token);
await page.goto(`${WEB}/login`);
await page.evaluate(({ t, e }) => { localStorage.clear(); localStorage.setItem('iris_auth_token', t); localStorage.setItem('iris_auth_email', e); }, { t: token, e: email });
await page.goto(`${WEB}/parent`, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(3200);
await page.screenshot({ path: `${OUT}/v1-hub.png` });
await page.getByRole('button', { name: /وضع الطفل|Child Mode/i }).first().click();
await page.waitForTimeout(2200);
await page.screenshot({ path: `${OUT}/v2-child-home.png` });
await page.locator('.lc-header button:has-text("العودة")').first().click();
await page.waitForTimeout(900);
await page.screenshot({ path: `${OUT}/v3-parent-gate.png` });
// letters deep link visual (lazy chunk + ChildShell)
await page.goto(`${WEB}/play/letters`, { waitUntil: 'domcontentloaded' });
await page.waitForTimeout(3500);
await page.screenshot({ path: `${OUT}/v4-letters-deeplink.png` });
console.log('visuals done');
await browser.close();
