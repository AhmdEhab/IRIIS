#!/usr/bin/env node
/* P71 MANIFEST — merge the legacy-UI narration set (/tmp/p71-map.json, keyed by
   the exact clean spoken text) together with the P70 set (/tmp/p70-map.json)
   into src/App/audio/fileClips.generated.ts. P70 wins on text collisions
   (those clips were verified first and the voice is identical anyway). */
import { readFileSync, writeFileSync, existsSync } from 'fs';

const p70 = JSON.parse(readFileSync('/tmp/p70-map.json', 'utf-8'));
const p71 = existsSync('/tmp/p71-map.json') ? JSON.parse(readFileSync('/tmp/p71-map.json', 'utf-8')) : {};
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');

const byText = new Map();
for (const v of Object.values(p70)) byText.set(v.spoken, v.file);
let added = 0;
for (const [text, v] of Object.entries(p71)) {
  if (byText.has(text)) continue;
  byText.set(text, v.file);
  added++;
}
const entries = [...byText.entries()].sort((a, b) => a[1].localeCompare(b[1]));
const body = entries.map(([t, f]) => `  "${esc(t)}": '/audio/tts/${f}',`).join('\n');
writeFileSync('src/App/audio/fileClips.generated.ts',
`/* P70+P71 — generated by scripts/p70-manifest.mjs + scripts/p71-manifest.mjs.
 * DO NOT EDIT BY HAND.
 * Full-app Arabic narration (ladder, caregiver cv2, ALL legacy screens,
 * stories, songs, life-skills steps, word curricula, badges, guidance
 * articles) in ONE consistent voice: ar-eg-tutor-11, warm and unhurried.
 * Keys are EXACTLY what AudioContext.cleanForSpeech produces (both sides run
 * through src/App/audio/speechText.js). Regenerate: collect-speech-strings.mjs
 * + p71-collect.mjs → generate_speech batches → p70-aligncut2/p71-cut →
 * p70-verify/p71-verify → the two manifest scripts.
 */
export const GENERATED_CLIPS: Record<string, string> = {
${body}
};
`);
console.log('total manifest entries:', entries.length, '| p71 added:', added);
