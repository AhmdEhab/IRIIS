#!/usr/bin/env node
/* P70 MANIFEST — turn /tmp/p70-map.json into src/App/audio/fileClips.generated.ts
   and merge it into the hand-made CLIPS table (only if not already merged). */
import { readFileSync, writeFileSync } from 'fs';

const map = JSON.parse(readFileSync('/tmp/p70-map.json', 'utf-8'));
const entries = Object.entries(map).sort((a, b) => a[1].file.localeCompare(b[1].file));
const esc = (s) => s.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/\n/g, '\\n');
const body = entries.map(([, v]) => `  "${esc(v.spoken)}": '/audio/tts/${v.file}',`).join('\n');
writeFileSync('src/App/audio/fileClips.generated.ts',
`/* P70 — generated by scripts/p70-manifest.mjs. DO NOT EDIT BY HAND.
 * Full-app Arabic narration (child ladder prompts + hints + app phrases +
 * caregiver questions) in one consistent voice: ar-eg-tutor-11, warm and
 * unhurried. Keys are EXACTLY what AudioContext.cleanForSpeech produces,
 * which is guaranteed because both sides run through
 * src/App/audio/speechText.js. Regenerate: scripts/collect-speech-strings.mjs
 * → generate_speech batches → scripts/p70-split.mjs → scripts/p70-verify.mjs
 * → this script.
 */
export const GENERATED_CLIPS: Record<string, string> = {
${body}
};
`);

let fc = readFileSync('src/App/audio/fileClips.ts', 'utf-8');
if (!fc.includes('GENERATED_CLIPS')) {
  fc = fc.replace(
    'const CLIPS: Record<string, string> = {',
    "import { GENERATED_CLIPS } from './fileClips.generated';\n\nconst CLIPS: Record<string, string> = {");
  fc = fc.replace('export function fileClipFor(',
    "// P70: the full-app narration set (298 phrases) merges in; the original\n// 42 word/sentence clips above win on any collision (they were tuned first).\nfor (const [k, v] of Object.entries(GENERATED_CLIPS)) if (!(k in CLIPS)) CLIPS[k] = v;\n\nexport function fileClipFor(");
  writeFileSync('src/App/audio/fileClips.ts', fc);
}
console.log('manifest entries:', entries.length, '| fileClips merged:', fc.includes('GENERATED_CLIPS'));
